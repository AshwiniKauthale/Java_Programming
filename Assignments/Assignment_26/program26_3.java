class program26_3
{
    public static void main(String A[])
    {
        int iValue  = 0;
        Scanner sobj = new Scanner(System.in);

        System.out.println("Enter the Frequency :");
        iValue = sobj.nextInt();

        Pattern pobj = new Pattern();
        pobj.Display(iValue);
    }
}
