///////////////////////////////////////////////////////////////////

class program37_5
{
    public static void main(String A[])
    {
        Scanner scanobj = new Scanner(System.in);

        System.out.println("Enter String :");
        String sobj = scanobj.nextLine();


        Strings strobj = new Strings();

        strobj.ReverseDisplay(sobj);

        strobj = null;
        sobj = null;
        scanobj = null;

        System.gc();
    }
}


